const LanguageContext = createContext(null);
export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
};

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('katalogu-lipjan-language') || 'sq');
  useEffect(() => {
    localStorage.setItem('katalogu-lipjan-language', language);
    document.documentElement.lang = language;
  }, [language]);
  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key) => dictionaries[language]?.[key] ?? dictionaries.sq[key] ?? key,
    tr: (source) => language === 'en' ? (englishText[source] ?? source) : source,
  }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}
